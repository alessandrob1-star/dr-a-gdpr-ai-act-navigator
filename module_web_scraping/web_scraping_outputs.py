def write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, default=str), encoding="utf-8")


def write_markdown_summary(
    path: Path, summary: dict[str, Any], events: list[dict[str, Any]]
) -> None:
    lines = [
        "# Web Scraping Output Summary",
        "",
        "This file is generated by the deterministic web scraping output command.",
        "It shows concrete files produced by the MVP pipeline without relying on a",
        "web app or live network access.",
        "",
        "## Generated Outputs",
        "",
        f"- Source snapshot: `{summary['source_snapshot']}`",
        f"- Scraped monitored items: `{summary['scraped_items_file']}`",
        f"- Seed monitored items: `{summary['seed_items_file']}`",
        f"- Regulatory events: `{summary['events_file']}`",
        f"- Run summary: `{summary['summary_file']}`",
        "",
        "## Run Counts",
        "",
        f"- Sources loaded: {summary['sources_loaded']}",
        f"- Static scraped items: {summary['static_scraped_items']}",
        f"- Seed monitored items: {summary['seed_monitored_items']}",
        f"- Regulatory events: {summary['regulatory_events']}",
        "",
        "## Validation Status Counts",
        "",
    ]
    for status, count in summary["status_counts"].items():
        lines.append(f"- {status}: {count}")

    lines.extend(["", "## Priority Counts", ""])
    for priority, count in summary["priority_counts"].items():
        lines.append(f"- {priority}: {count}")

    lines.extend(["", "## Example Events", ""])
    for event in events[:5]:
        lines.extend(
            [
                f"### {event['event_title']}",
                "",
                f"- Status: {event['event_status']}",
                f"- Priority: {event['overall_priority']}",
                f"- Regulation area: {event['regulation_area']}",
                f"- Evidence count: {event['evidence_count']}",
                f"- Recommended attention: {event['recommended_attention']}",
                "",
                event["summary"],
                "",
            ]
        )

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def event_badge(status: str) -> str:
    return {
        "A_OFFICIALLY_PUBLISHED": "Official publication",
        "B_OFFICIAL_DRAFT": "Official draft/guidance",
        "C_UNCONFIRMED_NEWS": "Trusted news warning",
    }.get(status, status)


def build_article_feed(
    static_items: list[Any],
    events: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    feed: list[dict[str, Any]] = []
    for item in static_items:
        feed.append(
            {
                "title": item.title,
                "source": item.source_name,
                "url": item.url,
                "kind": "scraped_item",
                "status": "SCRAPED_MONITORED_ITEM",
                "status_label": "Scraped monitored item",
                "priority": "Review",
                "regulation_area": item.regulation_area,
                "topic_labels": item.topic_labels,
                "summary": item.summary
                or "Detected from a deterministic source-monitoring HTML sample.",
                "recommended_attention": "Review extracted item",
            }
        )

    for event in events:
        evidence = event.get("evidence", [])
        primary_evidence = evidence[0] if evidence else {}
        feed.append(
            {
                "title": event["event_title"],
                "source": primary_evidence.get("source_name", "Regulatory seed data"),
                "url": event.get("primary_official_source_url") or primary_evidence.get("url"),
                "kind": "regulatory_event",
                "status": event["event_status"],
                "status_label": event_badge(event["event_status"]),
                "priority": event["overall_priority"],
                "regulation_area": event["regulation_area"],
                "topic_labels": event["topic_labels"],
                "summary": event["summary"],
                "recommended_attention": event["recommended_attention"],
            }
        )
    return feed


def write_article_feed_markdown(path: Path, feed: list[dict[str, Any]]) -> None:
    lines = [
        "# Regulatory Articles and News Feed",
        "",
        "This feed is generated from deterministic MVP demo data. It shows the kind",
        "of articles, official updates, draft guidance, and trusted warnings that",
        "the platform can normalize for review.",
        "",
    ]
    for item in feed:
        lines.extend(
            [
                f"## {item['title']}",
                "",
                f"- Source: {item['source']}",
                f"- Status: {item['status_label']}",
                f"- Priority: {item['priority']}",
                f"- Regulation area: {item['regulation_area']}",
                f"- Topics: {', '.join(item['topic_labels']) if item['topic_labels'] else 'not detected'}",
                f"- Link: {item['url'] or 'not available'}",
                "",
                item["summary"],
                "",
            ]
        )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


