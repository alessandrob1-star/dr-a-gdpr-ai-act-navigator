def generate_web_scraping_outputs(
    source_registry: Path,
    event_seed: Path,
    output_dir: Path,
) -> dict[str, Any]:
    output_dir.mkdir(parents=True, exist_ok=True)

    sources = load_sources(source_registry)
    static_source = next(
        source for source in sources if source.name == "European Commission AI Office"
    )
    static_items = deduplicate_items(monitor_source_from_html(static_source, STATIC_HTML))
    seed_items = monitored_items_from_event_seed(event_seed, sources)
    events = [event.to_dashboard_dict() for event in group_items_into_events(seed_items)]

    source_snapshot_file = output_dir / "source_registry_snapshot.json"
    scraped_items_file = output_dir / "scraped_monitored_items.json"
    seed_items_file = output_dir / "seed_monitored_items.json"
    events_file = output_dir / "regulatory_events.json"
    article_feed_file = output_dir / "articles_and_news_feed.json"
    article_feed_markdown_file = output_dir / "articles_and_news_feed.md"
    article_feed_html_file = output_dir / "articles_and_news_feed.html"
    summary_file = output_dir / "run_summary.json"
    summary_markdown_file = output_dir / "run_summary.md"
    article_feed = build_article_feed(static_items, events)

    write_json(source_snapshot_file, [asdict(source) for source in sources])
    write_json(scraped_items_file, [asdict(item) for item in static_items])
    write_json(seed_items_file, [asdict(item) for item in seed_items])
    write_json(events_file, events)
    write_json(article_feed_file, article_feed)
    write_article_feed_markdown(article_feed_markdown_file, article_feed)
    write_article_feed_html(article_feed_html_file, article_feed)

    status_counts = Counter(event["event_status"] for event in events)
    priority_counts = Counter(event["overall_priority"] for event in events)
    summary = {
        "output_dir": str(output_dir),
        "source_snapshot": str(source_snapshot_file),
        "scraped_items_file": str(scraped_items_file),
        "seed_items_file": str(seed_items_file),
        "events_file": str(events_file),
        "article_feed_file": str(article_feed_file),
        "article_feed_markdown_file": str(article_feed_markdown_file),
        "article_feed_html_file": str(article_feed_html_file),
        "summary_file": str(summary_file),
        "summary_markdown_file": str(summary_markdown_file),
        "sources_loaded": len(sources),
        "static_scraped_items": len(static_items),
        "seed_monitored_items": len(seed_items),
        "regulatory_events": len(events),
        "article_feed_items": len(article_feed),
        "status_counts": dict(sorted(status_counts.items())),
        "priority_counts": dict(sorted(priority_counts.items())),
    }
    write_json(summary_file, summary)
    write_markdown_summary(summary_markdown_file, summary, events)
    return summary
